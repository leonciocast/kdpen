/**
 * Original animal silhouettes for puzzle grids.
 *
 * Every animal is a union of ellipses authored for this project. The outlines
 * are not copied from Neoformix, or from any other commercial word-search
 * product. All geometry is original and released with the rest of this app.
 */
import { Blob, e } from "./silhouettes";

export interface AnimalDef {
  key: string;
  label: string;
  /** Smallest N×N canvas that keeps the silhouette recognisable and ≥3 cells thick. */
  minSize: number;
  /** Theme / search aliases (lowercase). The label and key are matched too. */
  aliases: string[];
  blobs: Blob[];
  /** Optional torso box in the same coordinates as the blobs, used to sit a sudoku inside the body. */
  focus?: [number, number, number, number];
  /** Override the natural bounding-box aspect (width / height). */
  aspect?: number;
}

/** Four stout legs under a body. */
function legs(xs: number[], cy: number, rx: number, ry: number, rot: number[] = []): Blob[] {
  return xs.map((x, i) => e(x, cy, rx, ry, rot[i] ?? 0));
}

