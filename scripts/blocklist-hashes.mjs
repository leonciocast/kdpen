#!/usr/bin/env node
/**
 * Turn a plain blocklist (one token per line, A–Z) into the hashed data the generator ships
 * (src/lib/wordsearch/blocklistData.ts), so no blocked word is ever readable in the app or its bundle.
 *   node scripts/blocklist-hashes.mjs tokens.txt stems.txt > src/lib/wordsearch/blocklistData.ts
 * The plain lists stay outside the repo (the team's shared blocklist).
 */
import { readFileSync } from "fs";
const read = (p) => [...new Set(readFileSync(p, "utf8").split(/\s+/).map((t) => t.toUpperCase().replace(/[^A-Z]/g, "")).filter((t) => t.length >= 3))].sort();
const [tokensFile, stemsFile] = process.argv.slice(2);
if (!tokensFile || !stemsFile) throw new Error("usage: blocklist-hashes.mjs tokens.txt stems.txt");
// Must match tokenHash() in src/lib/wordsearch/blocklist.ts.
const tokenHash = (s) => {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193) >>> 0;
  return (h ^ Math.imul(s.length, 0x9e3779b1)) >>> 0;
};
const tokens = read(tokensFile);
const stems = read(stemsFile);
const lengths = [...new Set(tokens.map((t) => t.length))].sort((a, b) => a - b);
const hashes = [...new Set(tokens.map(tokenHash))].sort((a, b) => a - b);
const wrap = (xs, per) => xs.reduce((out, x, i) => (i % per ? (out[out.length - 1] += `, ${x}`) : out.push(`  ${x}`), out), []).join(",\n");
process.stdout.write(`/**
 * Generated by scripts/blocklist-hashes.mjs from the shared publishing blocklist (${tokens.length} tokens).
 * Blocked tokens are stored only as hashes so the list is never readable in the app; do not edit by hand.
 */
export const BLOCKED_TOKEN_LENGTHS = [${lengths.join(", ")}];
export const BLOCKED_TOKEN_HASHES: readonly number[] = [
${wrap(hashes, 8)},
];
/** Real words that contain a blocked token (a hit inside one of these, in the same reading, is fine). */
export const INNOCENT_STEMS: readonly string[] = [
${wrap(stems.map((s) => JSON.stringify(s)), 10)},
];
`);
